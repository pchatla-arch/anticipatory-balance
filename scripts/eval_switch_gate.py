"""Small paired diagnostic for command changes and nominal-to-BRACE switching.

For every scenario, a nominal reference supplies a world-frame launch position and
velocity. The six comparison arms replay those inputs with the same reset keys:
CONTINUE, nominal actor with a zero-command interval, and BRACE actor with that
interval, each with the projectile enabled or disabled. Disabling the projectile
does NOT mark the scenario as a miss or remove the scheduled command change.

This runs fixed checkpoints only. It does not train, install, commit, or push.
Default sample size is a GPU smoke diagnostic, not a statistical validation gate.
The output directory must not exist; interrupted runs remain available to inspect.
The default horizon does not guarantee 2.5 seconds of follow-up after every contact;
incomplete outcomes are reported as censored. A longer horizon can be requested.

Example (inside the existing Playground venv, from the repository root):
  python scripts/eval_switch_gate.py --nominal PATH --brace PATH --impl warp \
      --episodes 32 --batches 1 --lead 0.5 --hold 0.5 \
      --out results/switch_gate_v1
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import importlib.metadata
import json
import math
from pathlib import Path
import subprocess
import sys
import time


CONTROLLERS = ("continue", "nominal_zero_command", "brace_switch")
CONDITIONS = ("projectile", "no_projectile")
REQUIRED_METRICS = (
    "fell", "contact", "contact_step", "term_step", "pre_contact_failure",
    "post_contact_eligible", "post_contact_observed", "post_contact_censored",
    "survived_post_contact_window", "post_contact_followup_s",
    "progress_before_failure_m", "brace_duration_through_failure_s",
    "failure_inverted", "failure_self_contact", "failure_nonfinite", "failure_sustained_tilt",
)


def _arguments(argv=None):
  p = argparse.ArgumentParser(description=__doc__,
                              formatter_class=argparse.RawDescriptionHelpFormatter)
  p.add_argument("--nominal", required=True, help="nominal checkpoint or run directory")
  p.add_argument("--brace", required=True, help="BRACE checkpoint or run directory")
  p.add_argument("--impl", choices=("warp", "jax"), default="warp")
  p.add_argument("--episodes", type=int, default=32, help="paired scenarios per batch")
  p.add_argument("--batches", type=int, default=1)
  p.add_argument("--lead", type=float, default=0.5, help="seconds before nominal arrival")
  p.add_argument("--hold", type=float, default=0.5, help="seconds after nominal arrival")
  p.add_argument("--steps", type=int, default=300)
  p.add_argument("--recovery_window", type=float, default=2.5, help="post-contact seconds")
  p.add_argument("--command_vx", type=float, default=0.5)
  p.add_argument("--out", default="results/switch_gate_v1")
  p.add_argument("--seed", type=int, default=100)
  a = p.parse_args(argv)
  for name in ("episodes", "batches", "steps"):
    if getattr(a, name) < 1:
      p.error(f"--{name} must be positive")
  for name in ("lead", "hold", "recovery_window", "command_vx"):
    if not math.isfinite(getattr(a, name)):
      p.error(f"--{name} must be finite")
  if a.lead < 0 or a.hold < 0 or a.recovery_window <= 0:
    p.error("lead/hold must be nonnegative and recovery_window must be positive")
  if a.seed < 0 or a.seed + a.batches - 1 >= 2**32:
    p.error("batch seeds must be in [0, 2**32)")
  if Path(a.out).expanduser().exists():
    p.error(f"output already exists: {a.out}; choose a new directory")
  return a


def _git(cwd, *args):
  try:
    r = subprocess.run(["git", "-C", str(cwd), *args], check=True,
                       capture_output=True, text=True, timeout=10)
    return r.stdout.strip()
  except (OSError, subprocess.SubprocessError):
    return None


def _manifest(args):
  root = Path(__file__).resolve().parents[1]
  paths = [Path(__file__).resolve()]
  paths += sorted((root / "foresight" / "eval").glob("*.py"))
  paths += sorted((root / "foresight" / "envs" / "g1_impact").glob("*.py"))
  versions = {}
  for name in ("jax", "jaxlib", "brax", "mujoco", "mujoco-mjx", "mujoco-warp",
               "warp-lang", "flax", "optax", "orbax-checkpoint", "numpy"):
    try:
      versions[name] = importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
      versions[name] = None
  return {
      "protocol": "switch_gate_v1", "arguments": vars(args),
      "source_commit": _git(root, "rev-parse", "HEAD"),
      "tracked_source_status": _git(root, "status", "--porcelain", "--untracked-files=no"),
      "source_sha256": {str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
                        for p in paths},
      "package_versions": versions, "python": sys.version,
      "validation": "Generated by this run; no claim of prior GPU validation.",
  }


def _json_value(value):
  if hasattr(value, "item"):
    value = value.item()
  if isinstance(value, dict):
    return {str(k): _json_value(v) for k, v in value.items()}
  if isinstance(value, (list, tuple)):
    return [_json_value(v) for v in value]
  if isinstance(value, float) and not math.isfinite(value):
    return None
  return value


def _save_json(path, value):
  path.write_text(json.dumps(_json_value(value), indent=2, allow_nan=False) + "\n")


def _save_rows(path, rows):
  if not rows:
    return
  exists = path.exists()
  fields = list(rows[0])
  if any(list(row) != fields for row in rows):
    raise RuntimeError("inconsistent CSV row schema")
  if exists:
    with path.open(newline="") as f:
      if next(csv.reader(f), None) != fields:
        raise RuntimeError(f"CSV schema changed during run: {path.name}")
  with path.open("a", newline="") as f:
    writer = csv.DictWriter(f, fieldnames=fields)
    if not exists:
      writer.writeheader()
    writer.writerows({k: _json_value(v) for k, v in row.items()} for row in rows)


def _summarize_arm(rows):
  n = len(rows)
  failures = sum(bool(r["fell"]) for r in rows)
  observed = [r for r in rows if bool(r["post_contact_observed"])]
  survivors = sum(r["survived_post_contact_window"] == 1 for r in observed)
  return {
      "n": n, "failures": failures, "failure_rate": failures / n,
      "contacts_recorded_total": sum(bool(r["contact"]) for r in rows),
      "failures_without_any_recorded_contact": sum(
          bool(r["fell"]) and not bool(r["contact"]) for r in rows),
      "contacts_before_or_at_first_failure": sum(
          bool(r["contact"]) and (r["term_step"] < 0 or r["contact_step"] <= r["term_step"])
          for r in rows),
      "pre_contact_failures": sum(bool(r["pre_contact_failure"]) for r in rows),
      "post_contact_eligible": sum(bool(r["post_contact_eligible"]) for r in rows),
      "post_contact_observed": len(observed),
      "post_contact_censored": sum(bool(r["post_contact_censored"]) for r in rows),
      "post_contact_window_survivals": survivors,
      "post_contact_window_failures": len(observed) - survivors,
      "post_contact_survival_rate_observed": survivors / len(observed) if observed else None,
      "mean_progress_before_failure_m": sum(r["progress_before_failure_m"] for r in rows) / n,
      "mean_brace_duration_through_failure_s":
          sum(r["brace_duration_through_failure_s"] for r in rows) / n,
      "first_failure_flags_may_overlap": {
          flag: sum(bool(r[flag]) for r in rows)
          for flag in ("failure_inverted", "failure_self_contact",
                       "failure_nonfinite", "failure_sustained_tilt")},
      "diagnostic_first_brace_readiness_count": sum(bool(r["brace_ready"]) for r in rows),
  }


def _paired(reference, treatment):
  a = {(r["batch"], r["pair_id"]): r for r in reference}
  b = {(r["batch"], r["pair_id"]): r for r in treatment}
  if len(a) != len(reference) or len(b) != len(treatment) or a.keys() != b.keys():
    raise RuntimeError("duplicate or mismatched paired scenario IDs")
  counts = {"both_fail": 0, "neither_fails": 0,
            "reference_only_fails": 0, "treatment_only_fails": 0}
  progress_difference = 0.0
  for key in a:
    fa, fb = bool(a[key]["fell"]), bool(b[key]["fell"])
    name = ("both_fail" if fb else "reference_only_fails") if fa else (
        "treatment_only_fails" if fb else "neither_fails")
    counts[name] += 1
    progress_difference += (b[key]["progress_before_failure_m"] -
                            a[key]["progress_before_failure_m"])
  n = len(a)
  return {"n_pairs": n, **counts,
          "failure_rate_difference_treatment_minus_reference":
              (counts["treatment_only_fails"] - counts["reference_only_fails"]) / n,
          "mean_paired_progress_difference_m": progress_difference / n}


def _summary(rows, args, dt, readiness_thresholds):
  groups = {f"{c}/{p}": [r for r in rows if r["controller"] == c and r["condition"] == p]
            for c in CONTROLLERS for p in CONDITIONS}
  expected = args.episodes * args.batches
  if any(len(r) != expected for r in groups.values()):
    raise RuntimeError("an arm has the wrong number of paired episodes")
  comparisons = {}
  for condition in CONDITIONS:
    for reference, treatment in (("continue", "nominal_zero_command"),
                                 ("nominal_zero_command", "brace_switch"),
                                 ("continue", "brace_switch")):
      key = f"{treatment}_vs_{reference}/{condition}"
      comparisons[key] = _paired(groups[f"{reference}/{condition}"],
                                  groups[f"{treatment}/{condition}"])
  for controller in CONTROLLERS:
    comparisons[f"projectile_vs_no_projectile/{controller}"] = _paired(
        groups[f"{controller}/no_projectile"], groups[f"{controller}/projectile"])
  switch = comparisons["brace_switch_vs_nominal_zero_command/no_projectile"]
  command = comparisons["nominal_zero_command_vs_continue/no_projectile"]
  return {
      "protocol": "switch_gate_v1",
      "status": "switch_failure" if switch["treatment_only_fails"] else "inconclusive",
      "status_rule": "Any new paired no-projectile failure versus the zero-command nominal actor "
                     "flags the BRACE switch for inspection; this is not a significance test.",
      "new_no_projectile_command_change_failures": command["treatment_only_fails"],
      "next_step": "Inspect paired failure traces and readiness before any retraining decision.",
      "paired_scenarios": expected, "comparison_rollouts": 6 * expected,
      "reference_rollouts": expected, "episodes_per_arm": expected,
      "dt_s": dt, "horizon_s": args.steps * dt,
      "lead_s_before_nominal_arrival": args.lead, "hold_s_after_nominal_arrival": args.hold,
      "recovery_window_s": args.recovery_window,
      "readiness": {
          "thresholds": readiness_thresholds,
          "interpretation": "Diagnostic sampled posture criterion; first qualifying event, "
                            "not a verified impact-safe state or maintained readiness at contact."},
      "population": "Fixed trained policies; scenarios paired across all six arms. "
                    "Contacts may differ across arms; contact-conditioned subsets are not paired.",
      "timing": "The switch uses nominal target arrival, not measured physical contact time.",
      "censoring": "Unknown post-contact outcomes are blank in CSV/null in JSON, not successes. "
                   "Observed-only rates must be read together with their censored counts.",
      "arms": {name: _summarize_arm(group) for name, group in groups.items()},
      "paired_comparisons": comparisons,
  }


def _check_array(name, actual, expected, atol=1e-6):
  import numpy as np
  actual, expected = np.asarray(actual), np.asarray(expected)
  if actual.shape != expected.shape or not np.all(np.isfinite(actual)) or not np.allclose(
      actual, expected, rtol=0.0, atol=atol):
    raise RuntimeError(f"paired-input invariant failed: {name}")


def _check_finite_trace(traj, term_step, *, name):
  """Reject numerical corruption in the executed prefix, preserving the raw archive."""
  import numpy as np
  T, N = np.asarray(traj["brace_active"]).shape
  term = np.asarray(term_step)
  if (term.shape != (N,) or not np.all(np.isfinite(term)) or
      np.any(term != np.floor(term)) or np.any((term < -1) | (term >= T))):
    raise RuntimeError(f"{name}: invalid first-failure indices")
  executed = np.arange(T)[:, None] <= np.where(term >= 0, term, T - 1)[None, :]
  for key in ("nonfinite_policy_input", "nonfinite_action", "nonfinite_physics"):
    flag = np.asarray(traj[key])
    if flag.shape != (T, N) or not np.all(np.isin(flag, [0, 1])):
      raise RuntimeError(f"{name}: invalid numeric-status flag {key}")
    bad = executed & flag.astype(bool)
    if np.any(bad):
      step, lane = np.argwhere(bad)[0]
      raise RuntimeError(f"{name}: {key} at executed step {step}, lane {lane}")
  for key in ("pelvis_pos", "pelvis_fwd", "torso_up", "com", "feet_pos",
              "proj_pos", "proj_vel"):
    value = np.asarray(traj[key])
    if value.shape[:2] != (T, N):
      raise RuntimeError(f"{name}: invalid trace shape for {key}")
    bad = executed & ~np.isfinite(value).reshape(T, N, -1).all(axis=-1)
    if np.any(bad):
      step, lane = np.argwhere(bad)[0]
      raise RuntimeError(f"{name}: nonfinite {key} at executed step {step}, lane {lane}")


def _run(args, out, manifest):
  # Keep --help and summary helper tests independent of the GPU Python stack.
  import inspect
  import jax
  import jax.numpy as jp
  import numpy as np
  import mujoco_playground
  from foresight.eval import rollout as R
  from foresight.eval.metrics import brace_readiness

  for name in ("projectile_enabled", "fixed_launch_pos", "fixed_launch_vel"):
    if name not in inspect.signature(R.set_scenario).parameters:
      raise RuntimeError(f"integrated rollout patch is required: set_scenario lacks {name}")
  if "recovery_window_s" not in inspect.signature(R.episode_table).parameters:
    raise RuntimeError("integrated episode_table recovery-window patch is required")
  nominal_path, brace_path = R.latest_checkpoint(args.nominal), R.latest_checkpoint(args.brace)
  nominal, brace_policy = R.load_policy(nominal_path), R.load_policy(brace_path)
  env = R.make_env(skill="nominal", impl=args.impl, overrides={"episode_length": args.steps})
  dt, n = float(env.dt), args.episodes
  readiness_thresholds = {
      "target_pelvis_height": float(env._config.brace.base_height_target),
      "height_tolerance": 0.05, "min_torso_up": 0.9,
      "min_foot_separation": 0.30, "dwell_s": 0.10,
  }
  pg_dir = Path(mujoco_playground.__file__).resolve().parent
  manifest.update({"resolved_checkpoints": {"nominal": str(nominal_path), "brace": str(brace_path)},
                   "playground_module": str(pg_dir),
                   "playground_source_commit": _git(pg_dir, "rev-parse", "HEAD"),
                   "devices": [str(d) for d in jax.devices()], "dt_s": dt,
                   "readiness_thresholds": readiness_thresholds,
                   "trace_archives": "batch_NNN_CONTROLLER.npz; arrays indexed (step, lane, ...). "
                                     "pair_id and projectile_enabled_input identify lanes."})
  _save_json(out / "manifest.json", manifest)
  all_rows = []
  for batch in range(args.batches):
    seed = args.seed + batch
    rng, draws = jax.random.PRNGKey(seed), np.random.RandomState(seed)
    reset_keys = jax.random.split(jax.random.fold_in(rng, 1), n)
    masses = draws.uniform(*env._config.impact.mass_range, n).astype(np.float32)
    speeds = draws.uniform(*env._config.impact.speed_range, n).astype(np.float32)
    hit_times = draws.uniform(*env._config.impact.hit_time_range, n).astype(np.float32)
    command = [args.command_vx, 0.0, 0.0]

    def reference_scenario(state):
      return R.set_scenario(env, state, speed=speeds, hit_time=hit_times,
                            is_miss=np.zeros(n, bool), command=command, projectile_enabled=True)

    ref_info, ref_traj = R.rollout(env, R.batched_env(env, masses), nominal, rng, args.steps,
                                   scenario_fn=reference_scenario, reset_keys=reset_keys)
    np.savez_compressed(out / f"batch_{batch:03d}_reference.npz",
                        pair_id=np.arange(batch * n, (batch + 1) * n),
                        projectile_enabled_input=np.ones(n, bool), **ref_traj)
    _check_finite_trace(ref_traj, ref_info["term_step"], name=f"batch {batch} reference")
    del ref_traj
    if not np.all(ref_info["proj_launched"]):
      raise RuntimeError("reference did not launch every projectile; no scenarios were silently dropped")
    positions = np.asarray(ref_info["proj_launch_pos"], np.float32)
    velocities = np.asarray(ref_info["proj_launch_vel"], np.float32)
    if positions.shape != (n, 3) or velocities.shape != (n, 3):
      raise RuntimeError("reference launch vectors must have shape (episodes, 3)")
    _check_array("finite reference launch positions", positions, positions)
    _check_array("finite reference launch velocities", velocities, velocities)
    keys_np = np.asarray(reset_keys)
    scenarios = []
    for i in range(n):
      row = {"batch": batch, "pair_id": batch * n + i, "within_batch_id": i, "seed": seed,
             "resetkey0": int(keys_np[i, 0]), "resetkey1": int(keys_np[i, 1]),
             "mass": float(masses[i]), "speed": float(speeds[i]),
             "requested_hit_time_s": float(hit_times[i]),
             "t_hit_nominal": float(ref_info["t_hit_nominal"][i]),
             "reference_launch_step": int(ref_info["proj_launch_step"][i]),
             "reference_fell": bool(ref_info["fell"][i]),
             "reference_contact": bool(ref_info["impact_contact"][i]),
             "reference_contact_step": int(ref_info["contact_step"][i]),
             "reference_term_step": int(ref_info["term_step"][i])}
      for axis, j in zip("xyz", range(3)):
        row[f"launch_pos_{axis}"] = float(positions[i, j])
        row[f"launch_vel_{axis}"] = float(velocities[i, j])
      scenarios.append(row)
    _save_rows(out / "scenarios.csv", scenarios)

    paired_keys = jp.concatenate([reset_keys, reset_keys], axis=0)
    enabled = np.concatenate([np.ones(n, bool), np.zeros(n, bool)])
    replay_positions, replay_velocities = np.tile(positions, (2, 1)), np.tile(velocities, (2, 1))
    replay_env = R.batched_env(env, np.tile(masses, 2))

    def replay_scenario(state):
      return R.set_scenario(
          env, state, speed=np.tile(speeds, 2), hit_time=np.tile(hit_times, 2),
          is_miss=np.zeros(2 * n, bool), command=command, projectile_enabled=enabled,
          fixed_launch_pos=replay_positions, fixed_launch_vel=replay_velocities)

    schedule = R.oracle_brace(jp.full((2 * n,), args.lead), args.hold, dt)
    for controller in CONTROLLERS:
      scheduled = controller != "continue"
      actor = brace_policy if controller == "brace_switch" else nominal
      info, traj = R.rollout(
          env, replay_env, nominal, rng, args.steps,
          brace_policy=actor if scheduled else None,
          decide=schedule if scheduled else R.no_brace,
          scenario_fn=replay_scenario, reset_keys=paired_keys)
      np.savez_compressed(out / f"batch_{batch:03d}_{controller}.npz",
                          pair_id=np.tile(np.arange(batch * n, (batch + 1) * n), 2),
                          projectile_enabled_input=enabled, **traj)
      _check_finite_trace(traj, info["term_step"], name=f"batch {batch} {controller}")
      _check_array("masses", info["proj_mass"], np.tile(masses, 2))
      _check_array("speeds", info["proj_speed"], np.tile(speeds, 2))
      _check_array("nominal arrival", info["t_hit_nominal"], np.tile(ref_info["t_hit_nominal"], 2))
      _check_array("launch steps", info["proj_launch_step"], np.tile(ref_info["proj_launch_step"], 2), 0)
      _check_array("projectile enabled flags", info["proj_enabled"], enabled, 0)
      _check_array("fixed trajectory flags", info["proj_fixed_trajectory"], np.ones(2 * n, bool), 0)
      _check_array("scenario miss flags", info["proj_is_miss"], np.zeros(2 * n, bool), 0)
      _check_array("fixed launch positions", info["proj_fixed_launch_pos"], replay_positions)
      _check_array("fixed launch velocities", info["proj_fixed_launch_vel"], replay_velocities)
      _check_array("enabled launch positions", info["proj_launch_pos"][:n], positions)
      _check_array("enabled launch velocities", info["proj_launch_vel"][:n], velocities)
      if not np.all(info["proj_launched"][:n]) or np.any(info["proj_launched"][n:]):
        raise RuntimeError("projectile enable/disable did not preserve the assigned arms")
      if np.any(info["impact_contact"][n:]):
        raise RuntimeError("disabled-projectile control recorded a projectile contact")
      expected_brace = np.zeros((args.steps, 2 * n), bool)
      # Compute schedule using the same float32 arithmetic as the rollout rule.
      if scheduled:
        expected_brace = np.asarray((jp.arange(args.steps, dtype=jp.float32)[:, None] * dt >=
                                    jp.asarray(info["t_hit_nominal"])[None, :] - args.lead) &
                                   (jp.arange(args.steps, dtype=jp.float32)[:, None] * dt <=
                                    jp.asarray(info["t_hit_nominal"])[None, :] + args.hold))
      _check_array("identical nominal brace schedule", traj["brace_active"], expected_brace, 0)
      table = R.episode_table(info, traj, dt, recovery_window_s=args.recovery_window)
      table.update(brace_readiness(
          traj["pelvis_pos"], traj["torso_up"], traj["feet_pos"], traj["feet_contact"],
          traj["brace_active"], info["term_step"], dt=dt, pelvis_fwd=traj["pelvis_fwd"],
          **readiness_thresholds))
      missing = set(REQUIRED_METRICS) - set(table)
      if missing:
        raise RuntimeError(f"required gate metrics are absent: {sorted(missing)}")
      if any(np.asarray(value).shape != (2 * n,) for value in table.values()):
        raise RuntimeError("episode-table columns must have one scalar per lane")
      for name in ("progress_before_failure_m", "brace_duration_through_failure_s"):
        if not np.all(np.isfinite(table[name])):
          raise RuntimeError(f"nonfinite comparison metric: {name}")
      observed = np.asarray(table["post_contact_observed"], bool)
      if not np.all(np.isin(np.asarray(table["survived_post_contact_window"])[observed], [0.0, 1.0])):
        raise RuntimeError("observed recovery outcomes must be finite binary values")
      batch_rows = []
      for lane in range(2 * n):
        i, condition = lane % n, CONDITIONS[lane // n]
        row = {"batch": batch, "pair_id": batch * n + i, "within_batch_id": i,
               "controller": controller, "condition": condition, "projectile_enabled_input": bool(enabled[lane])}
        row.update({k: v[lane].item() if hasattr(v[lane], "item") else v[lane] for k, v in table.items()})
        # Scenario inputs remain meaningful even when the projectile was disabled.
        for axis, j in zip("xyz", range(3)):
          row[f"fixed_launch_pos_{axis}"] = float(positions[i, j])
          row[f"fixed_launch_vel_{axis}"] = float(velocities[i, j])
        batch_rows.append(row)
      all_rows.extend(batch_rows)
      _save_rows(out / "episodes.csv", batch_rows)
      print(f"batch {batch} {controller}: " + "; ".join(
          f"{condition} failures={sum(bool(r['fell']) for r in batch_rows if r['condition'] == condition)}/{n}"
          for condition in CONDITIONS), flush=True)
      del traj
  return _summary(all_rows, args, dt, readiness_thresholds)


def main(argv=None):
  args = _arguments(argv)
  out = Path(args.out).expanduser()
  out.mkdir(parents=True, exist_ok=False)
  manifest = _manifest(args)
  _save_json(out / "manifest.json", manifest)
  start = time.monotonic()
  try:
    summary = _run(args, out, manifest)
    summary["elapsed_s"] = time.monotonic() - start
    _save_json(out / "summary.json", summary)
    print(json.dumps(_json_value(summary), indent=2, allow_nan=False), flush=True)
  except Exception as exc:
    _save_json(out / "summary.json", {"protocol": "switch_gate_v1", "status": "harness_failure",
                                     "error_type": type(exc).__name__, "error": str(exc),
                                     "elapsed_s": time.monotonic() - start})
    raise


if __name__ == "__main__":
  main()
